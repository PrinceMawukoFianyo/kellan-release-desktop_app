// ── Types ──────────────────────────────────────────────────────────────────────

interface Supplier {
  id: string;
  name: string;
  contactPerson?: string;
  email?: string;
  phone?: string;
}

interface Item {
  id: string;
  name: string;
  sku: string;
  description?: string;
  unitCost?: number;
  sellingPrice?: number;
}

interface DeliveryLocation {
  id: string;
  name: string;
  address?: string;
}

interface PurchaseOrderFormProps {
  suppliers: Supplier[];
  items: Item[];
  deliveryLocations: DeliveryLocation[];
  autoGeneratedPONumber: string;
  initialData?: {
    id: string;
    poNumber: string;
    supplierId: string;
    orderDate: string;
    expectedDeliveryDate: string;
    deliveryAddress: string;
    deliveryLocationId: string;
    notes?: string;
    shippingCost?: string;
    taxPercentage?: number;
    paymentTerms?: string;
    lineItems: LineItem[];
    paymentStatus?: "UNPAID" | "PARTIAL" | "PAID";
    status?: string;
  };
  onSuccess?: (po: any) => void;
  isLoading?: boolean;
}

interface PriceUpdateItem {
  itemId: string;
  itemName: string;
  oldCost: number;
  newCost: number;
  oldSelling: number;
  suggestedSelling: number;
}

// ── Component ──────────────────────────────────────────────────────────────────

export default function PurchaseOrderForm({
  suppliers,
  items,
  deliveryLocations,
  initialData,
  autoGeneratedPONumber,
  onSuccess,
  isLoading = false,
}: PurchaseOrderFormProps) {
  const [formData, setFormData] = useState({
    poNumber: initialData?.poNumber || autoGeneratedPONumber,
    supplierId: initialData?.supplierId || "",
    deliveryLocationId: initialData?.deliveryLocationId || "",
    orderDate: initialData?.orderDate || new Date().toISOString().split("T")[0],
    expectedDeliveryDate: initialData?.expectedDeliveryDate || "",
    deliveryAddress: initialData?.deliveryAddress || "",
    notes: initialData?.notes || "",
    shippingCost: initialData?.shippingCost || "0",
    taxPercentage: initialData?.taxPercentage?.toString() || "0",
    paymentTerms: initialData?.paymentTerms || "",
    paymentStatus: initialData?.paymentStatus || "UNPAID",
  });

  const [lineItems, setLineItems] = useState<LineItem[]>(initialData?.lineItems || []);
  const [isSubmitting, setIsSubmitting] = useState(false);
  const [supplierSearch, setSupplierSearch] = useState("");
  // ONE auto-receive option only (the duplicate "auto-create goods receipt"
  // checkbox was removed: it did the same thing and could double-count stock).
  const [autoReceiveGoods, setAutoReceiveGoods] = useState(false);
  const [sendDialogOpen, setSendDialogOpen] = useState(false);
  const [sending, setSending] = useState(false);
  const [activeTab, setActiveTab] = useState<"order" | "receive">("order");

  // Receive quantities state (lineId -> receiveNow)
  const [receiveQuantities, setReceiveQuantities] = useState<Record<string, number>>({});

  // Live item catalogue (cost + selling). Updated locally after an item's
  // price is changed so comparisons and suggestions never use stale values.
  const [catalog, setCatalog] = useState<Item[]>(items);

  // Price update queue
  const [priceUpdateQueue, setPriceUpdateQueue] = useState<PriceUpdateItem[]>([]);
  const [currentPriceUpdate, setCurrentPriceUpdate] = useState<PriceUpdateItem | null>(null);
  const [priceModalOpen, setPriceModalOpen] = useState(false);
  // Runs after the price review finishes (e.g. the redirect after saving)
  const pendingSuccessRef = useRef<(() => void) | null>(null);

  // When lineItems change, reset receive quantities
  useEffect(() => {
    const newQuantities: Record<string, number> = {};
    lineItems.forEach((item) => {
      const existing = receiveQuantities[item.id || item.itemId];
      newQuantities[item.id || item.itemId] = existing !== undefined ? existing : 0;
    });
    setReceiveQuantities(newQuantities);
  }, [lineItems]);

  // ── Price change review ─────────────────────────────────────────────────────

  // Compare each line's cost with the item's saved cost. The suggested selling
  // price keeps the old markup: newCost × (oldSelling / oldCost).
  const checkPriceChanges = (lines: LineItem[]): PriceUpdateItem[] => {
    const updates: PriceUpdateItem[] = [];
    const seen = new Set<string>();
    for (const line of lines) {
      if (!line.itemId || seen.has(line.itemId)) continue;
      seen.add(line.itemId);
      const cat = catalog.find((i) => i.id === line.itemId);
      if (!cat) continue;
      const oldCost = cat.unitCost ?? 0;
      const oldSelling = cat.sellingPrice ?? 0;
      const newCost = Number(line.unitPrice);
      if (!(newCost > 0) || Math.abs(newCost - oldCost) < 0.005) continue;
      const factor = oldCost > 0 && oldSelling > 0 ? oldSelling / oldCost : 1.25;
      updates.push({
        itemId: line.itemId,
        itemName: line.itemName,
        oldCost,
        newCost,
        oldSelling,
        suggestedSelling: Math.round(newCost * factor * 100) / 100,
      });
    }
    return updates;
  };

  const finishPriceReview = () => {
    setPriceModalOpen(false);
    setPriceUpdateQueue([]);
    setCurrentPriceUpdate(null);
    const next = pendingSuccessRef.current;
    pendingSuccessRef.current = null;
    next?.();
  };

  const handlePriceUpdateDecision = async (action: "both" | "cost" | "keep" | "skipAll") => {
    if (!currentPriceUpdate) return;
    if (action === "skipAll") {
      finishPriceReview();
      return;
    }

    if (action === "both" || action === "cost") {
      const selling =
        action === "both" ? currentPriceUpdate.suggestedSelling : currentPriceUpdate.oldSelling;
      try {
        const res: any = await updateItemCostAndPrice(
          currentPriceUpdate.itemId,
          currentPriceUpdate.newCost,
          selling
        );
        if (res && res.success === false) throw new Error(res.error || "Update failed");
        setCatalog((prev) =>
          prev.map((i) =>
            i.id === currentPriceUpdate.itemId
              ? { ...i, unitCost: currentPriceUpdate.newCost, sellingPrice: selling }
              : i
          )
        );
        toast.success(
          `Updated ${currentPriceUpdate.itemName}: cost → ${formatCurrency(
            currentPriceUpdate.newCost
          )}, selling → ${formatCurrency(selling)}`
        );
      } catch (err) {
        toast.error(`Failed to update ${currentPriceUpdate.itemName}`);
      }
    }

    const rest = priceUpdateQueue.filter((p) => p.itemId !== currentPriceUpdate.itemId);
    if (rest.length > 0) {
      setPriceUpdateQueue(rest);
      setCurrentPriceUpdate(rest[0]);
    } else {
      finishPriceReview();
    }
  };

  // ── Receipt scanner handler ─────────────────────────────────────────────────

  const handleExtracted = (data: ScannedPOData) => {
    setFormData((prev) => ({
      ...prev,
      supplierId: data.supplierId || prev.supplierId,
      deliveryLocationId: data.deliveryLocationId || prev.deliveryLocationId,
      orderDate: data.orderDate || prev.orderDate,
      expectedDeliveryDate: data.expectedDeliveryDate || prev.expectedDeliveryDate,
      deliveryAddress: data.deliveryAddress || prev.deliveryAddress,
      paymentTerms: data.paymentTerms || prev.paymentTerms,
      shippingCost: data.shippingCost || prev.shippingCost,
      notes: data.notes
        ? prev.notes
          ? `${prev.notes}\n${data.notes}`
          : data.notes
        : prev.notes,
    }));

    if (data.lineItems && data.lineItems.length > 0) {
      const mapped: LineItem[] = data.lineItems.map((li, idx) => ({
        id: `scanned-${Date.now()}-${idx}`,
        itemId: li.itemId || "",
        itemName: li.itemName || "",
        itemSku: li.itemSku || "",
        quantity: Number(li.quantity) || 1,
        unitPrice: Number(li.unitPrice) || 0,
        taxRate: Number(li.taxRate) || 0,
        lineTotal:
          Number(li.lineTotal) || (Number(li.quantity) || 1) * (Number(li.unitPrice) || 0),
        locationId: li.locationId || "",
        locationName: li.locationName || "",
      }));

      setLineItems(mapped);

      const unmatched = mapped.filter((m) => !m.itemId).length;
      if (unmatched > 0) {
        toast.warning(`${unmatched} item(s) need manual selection`, {
          description: "Look for the amber warning on each unmatched row and pick the correct item.",
          duration: 6000,
        });
      } else {
        // Price changes are reviewed when you save the PO.
        toast.success(`All ${mapped.length} items matched to your catalogue!`);
      }

      const noLocation = mapped.filter((m) => !m.locationId).length;
      if (noLocation > 0) {
        toast.info(`Use "Apply to all" to set delivery locations`, {
          description: `${noLocation} row(s) have no location yet. Pick once and push to all.`,
          duration: 5000,
        });
      }
    } else {
      toast.warning("No line items were extracted", {
        description:
          "Try a clearer image or use Paste Text to enter receipt details manually.",
      });
    }
  };

  // ── Form helpers ────────────────────────────────────────────────────────────
  // Fields where a user could type a monetary/cost value — rounded to 5
  // decimal places on blur so a mis-typed 6th+ digit doesn't sneak into the
  // total. onChange is left alone so the user can type freely.
  const DECIMAL_ROUNDED_FIELDS = new Set(["shippingCost", "taxPercentage"]);
  const MAX_PRICE_DECIMALS = 5;

  const roundToDecimals = (value: string, maxDecimals: number = MAX_PRICE_DECIMALS) => {
    if (value.trim() === "") return value;
    const num = parseFloat(value);
    if (isNaN(num)) return value;
    let str = num.toFixed(maxDecimals);
    if (str.includes(".")) {
      str = str.replace(/0+$/, "").replace(/\.$/, "");
    }
    return str;
  };

  const handleInputChange = (
    e: React.ChangeEvent<HTMLInputElement | HTMLTextAreaElement | HTMLSelectElement>
  ) => {
    const { name, value } = e.target;
    setFormData((prev) => ({ ...prev, [name]: value }));
  };

  const handleInputBlur = (
    e: React.FocusEvent<HTMLInputElement | HTMLTextAreaElement | HTMLSelectElement>
  ) => {
    const { name, value } = e.target;
    if (!DECIMAL_ROUNDED_FIELDS.has(name)) return;
    setFormData((prev) => ({ ...prev, [name]: roundToDecimals(value) }));
  };

  const handleSelectChange = (name: string, value: string) => {
    setFormData((prev) => ({ ...prev, [name]: value }));
  };

  const calculateTotal = () => {
    const subtotal = lineItems.reduce((sum, item) => {
      const total =
        typeof item.lineTotal === "number"
          ? item.lineTotal
          : typeof item.lineTotal === "string"
          ? parseFloat(item.lineTotal)
          : (item.lineTotal as any).toNumber?.() ?? 0;
      return sum + total;
    }, 0);
    return subtotal + (parseFloat(formData.shippingCost) || 0);
  };

  // Update receive quantity for a line
  const updateReceiveQuantity = (lineId: string, value: number) => {
    const line = lineItems.find((l) => (l.id || l.itemId) === lineId);
    if (!line) return;
    const max = line.quantity;
    const newValue = Math.min(Math.max(0, value), max);
    setReceiveQuantities((prev) => ({ ...prev, [lineId]: newValue }));
  };

  // Check if any item will be received
  const hasItemsToReceive = Object.values(receiveQuantities).some((q) => q > 0);

  // Group receipt items by their individual location and create one goods
  // receipt per location group, so each item lands in the location it was
  // actually assigned. Receipts run ONE AT A TIME (not in parallel) so they
  // cannot race each other on the same purchase order, and we stop at the
  // first failure.
  type ReceiptItemInput = {
    purchaseOrderLineId: string;
    itemId: string;
    receivedQuantity: number;
    notes?: string;
    locationId: string;
  };

  const receiveGoodsGroupedByLocation = async (
    purchaseOrderId: string,
    receiptItems: ReceiptItemInput[],
    notes: string
  ) => {
    const groups = new Map<string, ReceiptItemInput[]>();
    for (const item of receiptItems) {
      const locId = item.locationId || formData.deliveryLocationId;
      if (!locId) continue;
      if (!groups.has(locId)) groups.set(locId, []);
      groups.get(locId)!.push(item);
    }

    const results: Awaited<ReturnType<typeof createGoodsReceipt>>[] = [];
    for (const [locId, locItems] of Array.from(groups.entries())) {
      const r = await createGoodsReceipt({
        purchaseOrderId,
        locationId: locId,
        notes,
        items: locItems.map(({ locationId, ...rest }) => rest),
      });
      results.push(r);
      if (!r.success) break;
    }

    return {
      allSucceeded: results.length > 0 && results.every((r) => r.success),
      locationCount: groups.size,
      results,
    };
  };

  // ── Submit handler with immediate receive ───────────────────────────────────

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    if (isSubmitting) return; // guard against double submits

    if (!formData.poNumber.trim()) {
      toast.error("PO Number is required");
      return;
    }
    if (!formData.supplierId) {
      toast.error("Supplier is required");
      return;
    }
    if (lineItems.length === 0) {
      toast.error("At least one line item is required");
      return;
    }

    const unmatchedItems = lineItems.filter((l) => !l.itemId);
    if (unmatchedItems.length > 0) {
      toast.error(`${unmatchedItems.length} line item(s) have no item selected`, {
        description: "Please select an item for every row before saving.",
      });
      return;
    }

    const itemsWithLocation = lineItems.map((li) => ({
      ...li,
      locationId: li.locationId || formData.deliveryLocationId || undefined,
    }));

    const missingLocation = itemsWithLocation.filter((l) => !l.locationId);
    if (missingLocation.length > 0) {
      toast.error(`${missingLocation.length} line item(s) have no delivery location`, {
        description:
          "Set a default location at the top of the form, or use 'Apply to all' in the line items section.",
      });
      return;
    }

    setIsSubmitting(true);
    try {
      const totalAmount = calculateTotal();
      const paidAmount =
        formData.paymentStatus === "PAID"
          ? totalAmount
          : formData.paymentStatus === "PARTIAL"
          ? totalAmount * 0.5
          : 0;
      const owingAmount = totalAmount - paidAmount;

      const serverLineItems = itemsWithLocation.map((item) => ({
        id: item.id && !item.id.startsWith("scanned-") ? item.id : undefined,
        itemId: item.itemId,
        quantity: item.quantity,
        unitPrice: item.unitPrice,
        taxRate: item.taxRate,
        locationId: item.locationId,
      }));

      const data = {
        poNumber: formData.poNumber,
        supplierId: formData.supplierId,
        deliveryLocationId: formData.deliveryLocationId || itemsWithLocation[0]?.locationId,
        orderDate: formData.orderDate,
        expectedDeliveryDate: formData.expectedDeliveryDate,
        deliveryAddress: formData.deliveryAddress,
        notes: formData.notes || undefined,
        shippingCost: formData.shippingCost,
        taxPercentage: parseInt(formData.taxPercentage) || 0,
        paymentTerms: formData.paymentTerms || undefined,
        paymentStatus: formData.paymentStatus,
        amountPaid: paidAmount,
        amountOwing: owingAmount,
        lineItems: serverLineItems,
      };

      let result;
      if (initialData?.id) {
        result = await updatePurchaseOrder(initialData.id, data);
        if (result.success) {
          toast.success("Purchase Order updated successfully");
        } else {
          throw new Error(result.error || "Update failed");
        }
      } else {
        result = await createPurchaseOrder(data);
        if (result.success) {
          toast.success("Purchase Order created successfully");
        } else {
          throw new Error(result.error || "Creation failed");
        }
      }

      // Handle immediate receiving (if any quantities entered in Receive tab)
      if (result.success && result.data?.id && hasItemsToReceive) {
        const freshPO = await getPurchaseOrderById(result.data.id);
        if (freshPO && freshPO.lines.length > 0) {
          const lineIdMap = new Map();
          freshPO.lines.forEach((line: any) => {
            lineIdMap.set(line.itemId, line.id);
          });

          const receiptItems: ReceiptItemInput[] = [];
          for (const line of lineItems) {
            const key = line.id || line.itemId;
            const receiveNow = receiveQuantities[key] || 0;
            if (receiveNow <= 0) continue;
            const realLineId = lineIdMap.get(line.itemId);
            if (!realLineId) {
              console.warn(`Could not find line id for item ${line.itemId}`);
              continue;
            }
            receiptItems.push({
              purchaseOrderLineId: realLineId,
              itemId: line.itemId,
              receivedQuantity: receiveNow,
              notes: "",
              locationId: line.locationId || formData.deliveryLocationId,
            });
          }

          if (receiptItems.length > 0) {
            const { allSucceeded, locationCount, results } = await receiveGoodsGroupedByLocation(
              result.data.id,
              receiptItems,
              `Immediate receipt from ${formData.paymentStatus === "UNPAID" ? "credit" : "paid"} purchase`
            );
            if (allSucceeded) {
              toast.success(
                locationCount > 1
                  ? `Received ${receiptItems.length} item(s) – stock dispersed to ${locationCount} locations`
                  : `Received ${receiptItems.length} item(s) – stock updated`
              );
            } else {
              const failMsgs = results.filter((r) => !r.success).map((r) => r.error).join(", ");
              toast.warning("PO saved but stock update failed: " + failMsgs);
            }
          }
        }
      } else if (autoReceiveGoods && !initialData?.id && result.success && result.data?.id) {
        // Auto-receive all items (full quantity). NEW orders only: when editing
        // an existing PO this would re-receive goods that may already be in stock.
        const freshPO = await getPurchaseOrderById(result.data.id);
        if (freshPO && freshPO.lines.length > 0) {
          const lineIdMap = new Map();
          freshPO.lines.forEach((line: any) => lineIdMap.set(line.itemId, line.id));
          const receiptItems = lineItems
            .filter((item) => item.quantity > 0)
            .map((item) => {
              const realLineId = lineIdMap.get(item.itemId);
              if (!realLineId) return null;
              return {
                purchaseOrderLineId: realLineId,
                itemId: item.itemId,
                receivedQuantity: item.quantity,
                notes: "",
                locationId: item.locationId || formData.deliveryLocationId,
              };
            })
            .filter(Boolean) as ReceiptItemInput[];
          if (receiptItems.length > 0) {
            const { allSucceeded, locationCount } = await receiveGoodsGroupedByLocation(
              result.data.id,
              receiptItems,
              `Auto‑generated from ${formData.paymentStatus === "UNPAID" ? "credit" : "paid"} purchase`
            );
            if (allSucceeded) {
              toast.success(
                locationCount > 1
                  ? `All goods received – stock dispersed to ${locationCount} locations`
                  : "All goods received – stock updated"
              );
            } else {
              toast.warning("PO saved but some stock updates failed");
            }
          }
        }
      }

      // Review cost changes before leaving the page. The redirect in onSuccess
      // is held until the price dialog is finished.
      if (result.success) {
        const updates = checkPriceChanges(lineItems);
        if (updates.length > 0) {
          pendingSuccessRef.current = () => onSuccess?.(result.data);
          setPriceUpdateQueue(updates);
          setCurrentPriceUpdate(updates[0]);
          setPriceModalOpen(true);
        } else {
          onSuccess?.(result.data);
        }
      }
    } catch (error) {
      toast.error("Failed to save Purchase Order", {
        description: error instanceof Error ? error.message : "An error occurred",
      });
    } finally {
      setIsSubmitting(false);
    }
  };

  // ── Send PO dialog handlers ─────────────────────────────────────────────────

  const handleSendEmail = async () => {
    setSending(true);
    const res = await sendPOToSupplier(formData.poNumber);
    if (res.success) toast.success("Email sent successfully");
    else toast.error(res.error);
    setSending(false);
    setSendDialogOpen(false);
  };

  const handleWhatsApp = () => {
    const supplier = suppliers.find((s) => s.id === formData.supplierId);
    if (!supplier?.phone) {
      toast.error("Supplier phone number not available");
      return;
    }
    const message = `Purchase Order ${formData.poNumber} from ${supplier.name}. Total: ${formatCurrency(
      calculateTotal()
    )}. Please confirm.`;
    window.open(
      `https://wa.me/${supplier.phone.replace(/\D/g, "")}?text=${encodeURIComponent(message)}`,
      "_blank"
    );
    setSendDialogOpen(false);
  };

  const handleTelegram = () => {
    const message = `Purchase Order ${formData.poNumber}. Total: ${formatCurrency(calculateTotal())}`;
    const url = `https://t.me/share/url?url=${encodeURIComponent(window.location.href)}&text=${encodeURIComponent(message)}`;
    window.open(url, "_blank");
    setSendDialogOpen(false);
  };

  return (
    <>
      <form onSubmit={handleSubmit} className="space-y-6">
        <Card>
          <CardHeader>
            <div className="flex items-center justify-between gap-3 flex-wrap">
              <CardTitle>
                {initialData ? "Edit Purchase Order" : "Create Purchase Order"}
              </CardTitle>
              <ReceiptScanner
                availableItems={catalog}
                availableSuppliers={suppliers}
                availableLocations={deliveryLocations}
                onExtracted={handleExtracted}
              />
            </div>
            <p className="text-xs text-muted-foreground">
              Fill manually, or use{" "}
              <span className="font-medium text-emerald-600">Scan Receipt / Invoice</span>{" "}
              to auto-fill.
            </p>
          </CardHeader>

          <CardContent>
            <Tabs value={activeTab} onValueChange={(v) => setActiveTab(v as any)} className="space-y-4">
              <TabsList className="grid w-full grid-cols-2">
                <TabsTrigger value="order">Order Details</TabsTrigger>
                <TabsTrigger value="receive" className="gap-2">
                  <PackageCheck className="h-4 w-4" />
                  Receive Items {hasItemsToReceive && `(${Object.values(receiveQuantities).reduce((a, b) => a + b, 0)} qty)`}
                </TabsTrigger>
              </TabsList>

              {/* Order Details Tab */}
              <TabsContent value="order" className="space-y-4">
                <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
                  {/* PO Number */}
                  <div className="space-y-2">
                    <Label htmlFor="poNumber">PO Number</Label>
                    <Input
                      id="poNumber" name="poNumber"
                      value={formData.poNumber}
                      onChange={handleInputChange}
                      disabled
                      className="bg-muted"
                    />
                  </div>

                  {/* Supplier */}
                  <div className="space-y-2">
                    <Label htmlFor="supplierId">Supplier *</Label>
                    <Select
                      value={formData.supplierId}
                      onValueChange={(v) => handleSelectChange("supplierId", v)}
                      disabled={isSubmitting || isLoading}
                    >
                      <SelectTrigger id="supplierId">
                        <SelectValue placeholder="Select supplier…" />
                      </SelectTrigger>
                      <SelectContent>
                        <div className="p-2 border-b sticky top-0 bg-background z-50">
                          <Input
                            placeholder="Search suppliers…"
                            value={supplierSearch}
                            onChange={(e) => setSupplierSearch(e.target.value)}
                            onClick={(e) => e.stopPropagation()}
                            className="h-8"
                          />
                        </div>
                        {suppliers
                          .filter((s) => s.name.toLowerCase().includes(supplierSearch.toLowerCase()))
                          .map((s) => (
                            <SelectItem key={s.id} value={s.id}>{s.name}</SelectItem>
                          ))}
                        {suppliers.filter((s) =>
                          s.name.toLowerCase().includes(supplierSearch.toLowerCase())
                        ).length === 0 && (
                          <div className="p-4 text-center text-sm text-muted-foreground">No suppliers found</div>
                        )}
                      </SelectContent>
                    </Select>
                  </div>

                  {/* Default Delivery Location */}
                  <div className="space-y-2">
                    <Label htmlFor="deliveryLocationId">Default Delivery Location</Label>
                    <Select
                      value={formData.deliveryLocationId || "__none__"}
                      onValueChange={(v) => handleSelectChange("deliveryLocationId", v === "__none__" ? "" : v)}
                      disabled={isSubmitting || isLoading}
                    >
                      <SelectTrigger id="deliveryLocationId">
                        <SelectValue placeholder="Select default location…" />
                      </SelectTrigger>
                      <SelectContent>
                        <SelectItem value="__none__">— None (set per line item) —</SelectItem>
                        {deliveryLocations.map((l) => (
                          <SelectItem key={l.id} value={l.id}>{l.name}</SelectItem>
                        ))}
                      </SelectContent>
                    </Select>
                    <p className="text-xs text-muted-foreground">
                      You can override per line item or use "Apply to all".
                    </p>
                  </div>

                  {/* Order Date */}
                  <div className="space-y-2">
                    <Label htmlFor="orderDate">Order Date</Label>
                    <Input
                      id="orderDate" name="orderDate" type="date"
                      value={formData.orderDate}
                      onChange={handleInputChange}
                      disabled={isSubmitting || isLoading}
                    />
                  </div>

                  {/* Expected Delivery Date */}
                  <div className="space-y-2">
                    <Label htmlFor="expectedDeliveryDate">Expected Delivery Date</Label>
                    <Input
                      id="expectedDeliveryDate" name="expectedDeliveryDate" type="date"
                      value={formData.expectedDeliveryDate}
                      onChange={handleInputChange}
                      disabled={isSubmitting || isLoading}
                    />
                  </div>

                  {/* Payment Status */}
                  <div className="space-y-2">
                    <Label htmlFor="paymentStatus">Payment Status</Label>
                    <Select
                      value={formData.paymentStatus}
                      onValueChange={(v) => handleSelectChange("paymentStatus", v)}
                    >
                      <SelectTrigger>
                        <SelectValue placeholder="Select payment status" />
                      </SelectTrigger>
                      <SelectContent>
                        <SelectItem value="UNPAID">Unpaid (Credit)</SelectItem>
                        <SelectItem value="PARTIAL">Partially Paid</SelectItem>
                        <SelectItem value="PAID">Paid</SelectItem>
                      </SelectContent>
                    </Select>
                  </div>
                </div>

                {/* Delivery Address */}
                <div className="space-y-2">
                  <Label htmlFor="deliveryAddress">Delivery Address</Label>
                  <Textarea
                    id="deliveryAddress" name="deliveryAddress"
                    value={formData.deliveryAddress}
                    onChange={handleInputChange}
                    placeholder="Enter delivery address…"
                    disabled={isSubmitting || isLoading}
                    rows={3}
                  />
                </div>

                {/* Notes */}
                <div className="space-y-2">
                  <Label htmlFor="notes">Notes</Label>
                  <Textarea
                    id="notes" name="notes"
                    value={formData.notes}
                    onChange={handleInputChange}
                    placeholder="Add any additional notes…"
                    disabled={isSubmitting || isLoading}
                    rows={2}
                  />
                </div>

                {/* Auto-receive: new orders only. To receive goods on an
                    existing order use the Receive Inventory button on the PO. */}
                {!initialData?.id && (
                  <div className="space-y-2 pt-2">
                    <div className="flex items-center space-x-2">
                      <Checkbox
                        id="autoReceive"
                        checked={autoReceiveGoods}
                        onCheckedChange={(checked) => setAutoReceiveGoods(!!checked)}
                      />
                      <Label htmlFor="autoReceive" className="cursor-pointer">
                        Receive ALL goods immediately (creates goods receipt and updates stock)
                      </Label>
                    </div>
                  </div>
                )}

                {/* Line Items Manager */}
                <LineItemsManager
                  lineItems={lineItems}
                  onLineItemsChange={setLineItems}
                  availableItems={catalog}
                  locations={deliveryLocations}
                  disabled={isSubmitting || isLoading}
                  onItemPriceUpdated={(id, cost, selling) =>
                    setCatalog((prev) =>
                      prev.map((i) =>
                        i.id === id ? { ...i, unitCost: cost, sellingPrice: selling } : i
                      )
                    )
                  }
                />
              </TabsContent>

              {/* Receive Items Tab */}
              <TabsContent value="receive" className="space-y-4">
                {lineItems.length === 0 ? (
                  <div className="text-center py-8 text-muted-foreground">
                    No line items added yet. Go to Order Details to add items.
                  </div>
                ) : (
                  <>
                    <div className="rounded-lg border overflow-hidden">
                      <table className="w-full text-sm">
                        <thead className="bg-muted/50">
                          <tr>
                            <th className="px-4 py-3 text-left">Item</th>
                            <th className="px-4 py-3 text-center">Ordered</th>
                            <th className="px-4 py-3 text-center">Previously Received</th>
                            <th className="px-4 py-3 text-center">Receive Now</th>
                          </tr>
                        </thead>
                        <tbody>
                          {lineItems.map((item) => {
                            const key = item.id || item.itemId;
                            const receiveNow = receiveQuantities[key] || 0;
                            const alreadyReceived = item.receivedQuantity || 0;
                            const remaining = item.quantity - alreadyReceived;
                            return (
                              <tr key={key} className="border-t">
                                <td className="px-4 py-3">
                                  <p className="font-medium">{item.itemName}</p>
                                  <p className="text-xs text-muted-foreground">{item.itemSku}</p>
                                </td>
                                <td className="px-4 py-3 text-center font-semibold">{item.quantity}</td>
                                <td className="px-4 py-3 text-center text-amber-600">{alreadyReceived}</td>
                                <td className="px-4 py-3 text-center">
                                  <Input
                                    type="number"
                                    min="0"
                                    max={remaining}
                                    value={receiveNow}
                                    onChange={(e) => updateReceiveQuantity(key, parseInt(e.target.value) || 0)}
                                    className="w-24 mx-auto text-center"
                                    disabled={isSubmitting}
                                  />
                                  <p className="text-xs text-muted-foreground mt-1">Max {remaining}</p>
                                </td>
                              </tr>
                            );
                          })}
                        </tbody>
                      </table>
                    </div>

                    {hasItemsToReceive && (
                      <div className="bg-blue-50 border border-blue-200 rounded-lg p-3">
                        <p className="text-sm text-blue-800">
                          <PackageCheck className="inline h-4 w-4 mr-1" />
                          You will receive {Object.values(receiveQuantities).reduce((a, b) => a + b, 0)} item(s) immediately.
                          Stock will be updated and PO status will change to "Partially Received" or "Received".
                        </p>
                      </div>
                    )}
                  </>
                )}
              </TabsContent>
            </Tabs>
          </CardContent>
        </Card>

        {/* Additional Info (outside tabs) */}
        <Card>
          <CardHeader><CardTitle>Additional Information</CardTitle></CardHeader>
          <CardContent className="space-y-4">
            <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
              <div className="space-y-2">
                <Label htmlFor="shippingCost">Shipping Cost</Label>
                <Input
                  id="shippingCost" name="shippingCost" type="number" step="0.00001" min="0"
                  value={formData.shippingCost}
                  onChange={handleInputChange}
                  onBlur={handleInputBlur}
                  placeholder="0.00"
                  disabled={isSubmitting || isLoading}
                />
              </div>
              <div className="space-y-2">
                <Label htmlFor="taxPercentage">Tax Percentage (%)</Label>
                <Input
                  id="taxPercentage" name="taxPercentage" type="number" step="0.00001" min="0" max="100"
                  value={formData.taxPercentage}
                  onChange={handleInputChange}
                  onBlur={handleInputBlur}
                  placeholder="0"
                  disabled={isSubmitting || isLoading}
                />
              </div>
              <div className="space-y-2 md:col-span-2">
                <Label htmlFor="paymentTerms">Payment Terms</Label>
                <Input
                  id="paymentTerms" name="paymentTerms"
                  value={formData.paymentTerms}
                  onChange={handleInputChange}
                  placeholder="e.g., Net 30, COD"
                  disabled={isSubmitting || isLoading}
                />
              </div>
            </div>
          </CardContent>
        </Card>

        {/* Total */}
        <Card className="bg-muted">
          <CardContent className="pt-6 flex justify-between items-center text-lg">
            <span className="font-semibold">Total:</span>
            <span className="text-2xl font-bold">{formatCurrency(calculateTotal())}</span>
          </CardContent>
        </Card>

        {/* Action Buttons */}
        <div className="flex gap-3 justify-end">
          <Button
            type="button"
            variant="outline"
            onClick={() => setSendDialogOpen(true)}
            className="gap-2"
            disabled={!formData.supplierId}
          >
            <Send className="h-4 w-4" /> Send to Supplier
          </Button>
          <Button
            type="submit"
            disabled={isSubmitting || isLoading}
            size="lg"
            className="gap-2"
          >
            {isSubmitting || isLoading ? "Saving…" : "Save Purchase Order"}
          </Button>
        </div>
      </form>

      {/* Price Update Modal */}
      <Dialog open={priceModalOpen} onOpenChange={(o) => !o && finishPriceReview()}>
        <DialogContent className="max-w-md">
          <DialogHeader>
            <DialogTitle>Update cost &amp; selling price?</DialogTitle>
            <DialogDescription>
              The cost on this order differs from the saved cost for{" "}
              <strong>{currentPriceUpdate?.itemName}</strong>.
              {priceUpdateQueue.length > 1 && ` (${priceUpdateQueue.length} items to review)`}
            </DialogDescription>
          </DialogHeader>
          {currentPriceUpdate && (
            <div className="bg-muted/30 p-3 rounded-lg space-y-2 text-sm">
              <div className="flex justify-between">
                <span>Saved cost</span>
                <span className="font-mono">{formatCurrency(currentPriceUpdate.oldCost)}</span>
              </div>
              <div className="flex justify-between">
                <span>New cost</span>
                <span className="font-mono font-bold text-amber-600">
                  {formatCurrency(currentPriceUpdate.newCost)}
                </span>
              </div>
              <div className="border-t my-2" />
              <div className="flex justify-between">
                <span>Saved selling</span>
                <span className="font-mono">{formatCurrency(currentPriceUpdate.oldSelling)}</span>
              </div>
              <div className="flex justify-between">
                <span>Old markup</span>
                <span className="font-mono">
                  {currentPriceUpdate.oldCost > 0
                    ? (
                        ((currentPriceUpdate.oldSelling - currentPriceUpdate.oldCost) /
                          currentPriceUpdate.oldCost) *
                        100
                      ).toFixed(1)
                    : "0.0"}
                  %
                </span>
              </div>
              <div className="space-y-1 pt-1">
                <Label className="text-xs">Suggested selling (editable)</Label>
                <Input
                  type="number"
                  step="0.01"
                  value={currentPriceUpdate.suggestedSelling}
                  onChange={(e) =>
                    setCurrentPriceUpdate({
                      ...currentPriceUpdate,
                      suggestedSelling: parseFloat(e.target.value) || 0,
                    })
                  }
                />
              </div>
            </div>
          )}
          <DialogFooter className="gap-2 flex-wrap">
            <Button variant="outline" onClick={() => handlePriceUpdateDecision("skipAll")}>
              Skip all
            </Button>
            <Button variant="secondary" onClick={() => handlePriceUpdateDecision("keep")}>
              Keep existing
            </Button>
            <Button variant="secondary" onClick={() => handlePriceUpdateDecision("cost")}>
              Cost only
            </Button>
            <Button onClick={() => handlePriceUpdateDecision("both")}>Update both</Button>
          </DialogFooter>
        </DialogContent>
      </Dialog>

      {/* Send PO Dialog */}
      <Dialog open={sendDialogOpen} onOpenChange={setSendDialogOpen}>
        <DialogContent className="max-w-md">
          <DialogHeader>
            <DialogTitle>Send Purchase Order</DialogTitle>
            <DialogDescription>
              Choose how to send PO #{formData.poNumber} to the supplier.
            </DialogDescription>
          </DialogHeader>
          <div className="space-y-3 py-4">
            <Button
              variant="outline"
              className="w-full justify-start gap-3"
              onClick={handleSendEmail}
              disabled={sending}
            >
              <Mail className="h-4 w-4" /> Send via Email
            </Button>
            <Button
              variant="outline"
              className="w-full justify-start gap-3"
              onClick={handleWhatsApp}
            >
              <MessageCircle className="h-4 w-4" /> Send via WhatsApp
            </Button>
            <Button
              variant="outline"
              className="w-full justify-start gap-3"
              onClick={handleTelegram}
            >
              <SendHorizonal className="h-4 w-4" /> Share via Telegram
            </Button>
          </div>
        </DialogContent>
      </Dialog>
    </>
  );
}
